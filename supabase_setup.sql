create or replace function public.lookup_login_email(p_identifier text)
returns text
language sql
stable
security definer
set search_path = public, auth
as $$
  with input as (
    select
      trim(coalesce(p_identifier, '')) as ident,
      regexp_replace(trim(coalesce(p_identifier, '')), '[^0-9]+', '', 'g') as digits
  )
  select u.email
  from public.users_profile p
  join auth.users u on u.id = p.id
  cross join input i
  where i.ident <> ''
    and coalesce(p.is_deleted, false) = false
    and coalesce(p.is_blocked, false) = false
    and (
      (
        p.full_name is not null
        and trim(p.full_name) <> ''
        and lower(trim(p.full_name)) = lower(i.ident)
      )
      or (
        i.digits <> ''
        and p.phone is not null
        and regexp_replace(p.phone, '[^0-9]+', '', 'g') = i.digits
      )
    )
  limit 1;
$$;

