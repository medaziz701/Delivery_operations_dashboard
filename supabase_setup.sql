create or replace function public.admin_set_user_role(p_user_id uuid, p_role text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_role text;
  v_admin_count integer;
  v_primary_admin uuid;
begin
  if not exists (
    select 1
    from public.users_profile me
    where me.id = auth.uid()
      and me.role = 'Admin'
  ) then
    raise exception 'not allowed';
  end if;

  select p.id into v_primary_admin
  from public.users_profile p
  where p.role = 'Admin'
    and coalesce(p.is_deleted, false) = false
  order by p.created_at asc
  limit 1;

  if p_user_id = auth.uid() then
    raise exception 'cannot change self role';
  end if;

  v_role := case when p_role is null then '' else trim(p_role) end;
  if v_role not in ('Admin', 'Tracking') then
    raise exception 'invalid role';
  end if;

  -- Prevent demoting the last admin.
  if v_role = 'Tracking' then
    if v_primary_admin is not null and p_user_id = v_primary_admin then
      raise exception 'cannot demote primary admin';
    end if;

    select count(*) into v_admin_count
    from public.users_profile
    where role = 'Admin'
      and coalesce(is_deleted, false) = false;

    if v_admin_count <= 1 then
      raise exception 'cannot demote last admin';
    end if;
  end if;

  update public.users_profile
  set role = v_role,
      -- If promoted to Admin, make sure it's not stuck in pending.
      is_approved = case when v_role = 'Admin' then true else is_approved end,
      updated_at = now()
  where id = p_user_id;
end;
$$;

