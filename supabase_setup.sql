create or replace function public.audit_trigger()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_old jsonb;
  v_new jsonb;
  v_pk text;
begin
  v_old := null;
  v_new := null;
  v_pk := null;

  if tg_op = 'INSERT' then
    v_new := to_jsonb(new);
    v_pk := coalesce(v_new ->> 'order_id', v_new ->> 'id');
  elsif tg_op = 'UPDATE' then
    v_old := to_jsonb(old);
    v_new := to_jsonb(new);
    v_pk := coalesce(v_new ->> 'order_id', v_new ->> 'id');
  elsif tg_op = 'DELETE' then
    v_old := to_jsonb(old);
    v_pk := coalesce(v_old ->> 'order_id', v_old ->> 'id');
  end if;

  insert into public.audit_logs (actor_id, action, table_name, record_pk, old_data, new_data, meta)
  values (auth.uid(), tg_op, tg_table_name, v_pk, v_old, v_new, null);

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

