create or replace function public.infer_order_status_from_message(
  p_from_role text,
  p_text text
)
returns table (
  status text,
  set_rejected_on_arrival boolean,
  set_has_issue boolean
)
language plpgsql
immutable
as $$
declare
  t text;
  r text;
begin
  t := public._normalize_msg_text(p_text);
  r := lower(trim(coalesce(p_from_role, '')));

  if t = '' then
    return;
  end if;

  if r = 'agent' then
    if t ~ '(وصلت|تم\s*التسليم|سلمت|تم\s*التوصيل|تم\s*الاستلام|استلم|استلم\s*الطلب|تم\s*توصيل\s*الطلب|وصل\s*الطلب|وصلت\s*للعميل|الطلب\s*وصل|تم\s*التسليم\s*بنجاح|تم\s*تسليم\s*الطلب|delivery\s*done|delivered|livr[eé]|livraison\s*faite|done|complete|completed)'
    then
      status := 'تم التسليم';
      set_rejected_on_arrival := false;
      set_has_issue := false;
      return next;
      return;
    end if;

    if t ~ '(رفض\b|رفض\s*الاستلام|الزبون\s*رفض|العميل\s*رفض|رفض\s*عند\s*الوصول|رفض\s*الطلب|ما\s*حبش\s*يستلم|ما\s*قبلش\s*الطلب|رفض\s*الباب|رجع\s*الطلب|مرجع|returned|refused|client\s*refused|رفض\s*المنتج|العميل\s*غير\s*رأيه)'
    then
      status := 'رفض عند الوصول';
      set_rejected_on_arrival := true;
      set_has_issue := false;
      return next;
      return;
    end if;

    if t ~ '(خرجت|في\s*الطريق|جاري\s*التوصيل|بالطريق|متجه\s*للعميل|قيد\s*التوصيل|سيتم\s*التوصيل|طريقه\s*للعميل|انطلقت|في\s*التوصيل|going|on\s*the\s*way|out\s*for\s*delivery|en\s*route|delivery\s*started)'
    then
      status := 'جاري التوصيل';
      set_rejected_on_arrival := false;
      set_has_issue := false;
      return next;
      return;
    end if;

    if t ~ '(مشكلة|ما\s*يرد|ما\s*يجاوب|لا\s*يرد|الهاتف\s*مغلق|\bمغلق\b|الرقم\s*مغلق|رقم\s*خطأ|الرقم\s*غير\s*صحيح|لا\s*يمكن\s*الاتصال|unreachable|no\s*answer|wrong\s*number|invalid\s*number|الزبون\s*غير\s*متوفر|العميل\s*غير\s*موجود|العنوان\s*خطأ|العنوان\s*غير\s*واضح|لم\s*نجد\s*العنوان|تأجيل|مؤجل)'
    then
      status := 'مشكلة';
      set_rejected_on_arrival := false;
      set_has_issue := true;
      return next;
      return;
    end if;
  elsif r = 'page' then
    if t ~ '(تم\s*التأكيد|confirmed|تأكيد\s*الطلب|تم\s*تأكيد\s*الطلب|الطلب\s*مؤكد|تم\s*تسجيل\s*الطلب|تم\s*إنشاء\s*الطلب|order\s*confirmed|validated|accepted|approved)'
    then
      status := 'قيد التنفيذ';
      set_rejected_on_arrival := false;
      set_has_issue := false;
      return next;
      return;
    end if;

    if t ~ '(إلغاء|الغاء|تم\s*الإلغاء|الطلب\s*ملغي|إلغاء\s*الطلب|cancel|cancelled|canceled|order\s*cancelled|تم\s*الغاء\s*الطلب)'
    then
      status := 'ملغي';
      set_rejected_on_arrival := false;
      set_has_issue := false;
      return next;
      return;
    end if;
  elsif r = 'customer' then
    if t ~ '(إلغاء|الغاء\s*الطلب|ألغيت\s*الطلب|ما\s*عاد\s*نحب\s*الطلب|ما\s*نحبش\s*الطلب|cancel|cancel\s*order|ألغيه|مش\s*حاب\s*الطلب)'
    then
      status := 'ملغي';
      set_rejected_on_arrival := false;
      set_has_issue := false;
      return next;
      return;
    end if;

    if t ~ '(رفض|رفض\s*الطلب|ما\s*نحبش\s*نستلم|لا\s*أريد\s*الطلب|لا\s*أريده|ما\s*نريده|ما\s*نحبش|رفض\s*الاستلام|ما\s*نحبش\s*الطلب)'
    then
      status := 'مرفوض';
      set_rejected_on_arrival := false;
      set_has_issue := false;
      return next;
      return;
    end if;
  end if;

  return;
end;
$$;

drop function if exists public.messages_auto_update_order_status() cascade;

create or replace function public.messages_auto_update_order_status()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  inf record;
begin
  if new.order_id is null then
    return new;
  end if;

  select * into inf
  from public.infer_order_status_from_message(new.from_role, new.text)
  limit 1;

  if inf is null or inf.status is null or trim(inf.status) = '' then
    return new;
  end if;

  update public.orders o
  set status = inf.status,
      rejected_on_arrival = case when coalesce(inf.set_rejected_on_arrival, false) then true else o.rejected_on_arrival end,
      has_issue = case when coalesce(inf.set_has_issue, false) then true else o.has_issue end
  where o.id = new.order_id
    and (o.status is distinct from inf.status);

  return new;
end;
$$;

